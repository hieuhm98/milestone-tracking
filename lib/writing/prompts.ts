export type WritingTaskKind = "task1" | "task2";

export interface DataTable {
  caption: string;
  columns: string[];
  rows: { label: string; values: (string | number)[] }[];
}

export interface WritingPrompt {
  id: string;
  task: WritingTaskKind;
  /** Short label shown on the picker. */
  title: string;
  /** Essay type (task 2) or visual type (task 1). */
  type: string;
  /** The instruction the candidate reads. */
  question: string;
  /** Task 1 only: the data the candidate must describe. */
  table?: DataTable;
}

